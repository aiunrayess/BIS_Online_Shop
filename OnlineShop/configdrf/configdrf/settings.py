# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases
#
# Local development intentionally falls back to SQLite. Set DATABASE_URL to a
# PostgreSQL URL in a deployed environment, for example:
# postgresql://onlineshop:password@db.example:5432/onlineshop?sslmode=require
# The URL is deliberately never logged so database credentials stay private.


def database_settings():
    database_url = os.environ.get('DATABASE_URL', '').strip()
    if not database_url:
        return {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': BASE_DIR / 'db.sqlite3',
            }
        }

    parsed = urlparse(database_url)
    scheme = parsed.scheme.lower()
    if scheme in ('postgres', 'postgresql'):
        database_name = unquote(parsed.path.lstrip('/'))
        if not database_name or not parsed.hostname:
            raise RuntimeError('DATABASE_URL must include a PostgreSQL host and database name.')
        try:
            port = parsed.port
        except ValueError as exc:
            raise RuntimeError('DATABASE_URL contains an invalid PostgreSQL port.') from exc

        query = parse_qs(parsed.query)
        sslmode = query.get(
            'sslmode',
            [os.environ.get('DJANGO_DB_SSLMODE', 'require' if not DEBUG else 'prefer')],
        )[0]
        return {
            'default': {
                'ENGINE': 'django.db.backends.postgresql',
                'NAME': database_name,
                'USER': unquote(parsed.username or ''),
                'PASSWORD': unquote(parsed.password or ''),
                'HOST': parsed.hostname,
                'PORT': str(port or 5432),
                'CONN_MAX_AGE': int(os.environ.get('DJANGO_DB_CONN_MAX_AGE', '60')),
                'CONN_HEALTH_CHECKS': True,
                'OPTIONS': {'sslmode': sslmode},
            }
        }

    if scheme == 'sqlite':
        database_name = unquote(parsed.path)
        if not database_name:
            raise RuntimeError('SQLite DATABASE_URL must include a database path.')
        return {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': database_name,
            }
        }

    raise RuntimeError('DATABASE_URL must use postgresql://, postgres://, or sqlite://.')


DATABASES = database_settings()


